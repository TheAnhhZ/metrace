"""Every machine-readable error code the API can return, in one place.

The UI maps these codes to Vietnamese messages (packages/api-client).
"""

from enum import StrEnum


class ReasonCode(StrEnum):
    # Generic
    VALIDATION_ERROR = "VALIDATION_ERROR"
    UNAUTHENTICATED = "UNAUTHENTICATED"
    FORBIDDEN = "FORBIDDEN"
    NOT_FOUND = "NOT_FOUND"
    CONFLICT = "CONFLICT"
    IDP_UNAVAILABLE = "IDP_UNAVAILABLE"
    SERVICE_UNAVAILABLE = "SERVICE_UNAVAILABLE"
    METHOD_NOT_ALLOWED = "METHOD_NOT_ALLOWED"
    UNSUPPORTED_MEDIA_TYPE = "UNSUPPORTED_MEDIA_TYPE"
    RATE_LIMITED = "RATE_LIMITED"
    INTERNAL_ERROR = "INTERNAL_ERROR"

    # Poka-yoke P1: receiving
    P1_MISSING_DOCUMENTS = "P1_MISSING_DOCUMENTS"
    P1_SUPPLIER_BLOCKED = "P1_SUPPLIER_BLOCKED"
    P1_SUPPLIER_CERT_EXPIRED = "P1_SUPPLIER_CERT_EXPIRED"
    P1_SUPPLIER_CERT_EXPIRING = "P1_SUPPLIER_CERT_EXPIRING"  # warning only
    P1_TEMP_OUT_OF_RANGE = "P1_TEMP_OUT_OF_RANGE"

    # Poka-yoke P2: cooking
    P2_MISSING_TIMESTAMPS = "P2_MISSING_TIMESTAMPS"
    P2_CORE_TEMP_BELOW_MIN = "P2_CORE_TEMP_BELOW_MIN"
    P2_INPUT_LOCKED = "P2_INPUT_LOCKED"

    # Poka-yoke P3: dispatch
    P3_MISSING_FORM_1 = "P3_MISSING_FORM_1"
    P3_MISSING_FORM_2 = "P3_MISSING_FORM_2"
    P3_MISSING_FORM_3 = "P3_MISSING_FORM_3"
    P3_DISH_NOT_IN_MENU = "P3_DISH_NOT_IN_MENU"
    P3_HOLD_TIME_EXCEEDED = "P3_HOLD_TIME_EXCEEDED"
    P3_SAMPLE_MISSING = "P3_SAMPLE_MISSING"
    P3_UPSTREAM_LOCKED = "P3_UPSTREAM_LOCKED"
    P3_SHIPMENT_HELD = "P3_SHIPMENT_HELD"
    P3_LINEAGE_TRUNCATED = "P3_LINEAGE_TRUNCATED"
    P3_SHIPMENT_EMPTY = "P3_SHIPMENT_EMPTY"

    # Poka-yoke P4: retained samples
    P4_SAMPLE_UNDER_MINIMUM = "P4_SAMPLE_UNDER_MINIMUM"
    P4_DISCARD_BEFORE_RETENTION = "P4_DISCARD_BEFORE_RETENTION"
    P4_DISCARD_DURING_INCIDENT = "P4_DISCARD_DURING_INCIDENT"

    # Files
    FILE_TOO_LARGE = "FILE_TOO_LARGE"
    FILE_TYPE_NOT_ALLOWED = "FILE_TYPE_NOT_ALLOWED"
    FILE_TYPE_MISMATCH = "FILE_TYPE_MISMATCH"
    FILE_EMPTY = "FILE_EMPTY"
