# Print a fresh .env with random secrets. `make init` redirects this to .env
# (only when .env does not exist yet). Never commit the output.
set -euo pipefail
umask 077

# Read a fixed amount of randomness and cut the result in bash: no reader closes a
# pipe early, so no "Broken pipe" noise (~250 usable characters per 1 KiB).
rand() {
  local chars
  chars=$(LC_ALL=C tr -dc 'A-Za-z0-9' < <(head -c 1024 /dev/urandom))
  printf '%s' "${chars:0:${1:-32}}"
}

# Unquoted heredoc: $(...) and backticks inside it RUN. Keep comments free of both.
cat <<EOF
# Generated by scripts/generate-dev-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Local secrets. Do NOT commit. Re-generate: make reset && rm .env && make init
# (volumes keep the old passwords, so reset them together)
POSTGRES_PASSWORD=$(rand)
KC_DB_PASSWORD=$(rand)
FLOWABLE_DB_PASSWORD=$(rand)
METRACE_MIGRATOR_PASSWORD=$(rand)
METRACE_APP_PASSWORD=$(rand)
KC_ADMIN_PASSWORD=$(rand)
METRACE_API_CLIENT_SECRET=$(rand)
SENSOR_GATEWAY_CLIENT_SECRET=$(rand)
FLOWABLE_ADMIN_PASSWORD=$(rand)
S3_ACCESS_KEY=$(rand 20)
S3_SECRET_KEY=$(rand 40)
DEMO_USER_PASSWORD=$(rand 16)
RATE_LIMIT_API_PER_MIN=600
RATE_LIMIT_READINGS_PER_MIN=1200
# Keycloak overlays (comma separated). Leave empty for demos; make dev-ports adds "test".
KC_OVERLAYS=
EOF
